#!/bin/bash
# Cross-publishes a self-contained, single-file win-x64 executable.
# Can be run from macOS/Linux/Windows — .NET doesn't need to run on Windows
# to produce a Windows build, only to execute the result.
set -euo pipefail
cd "$(dirname "$0")"

OUT="publish/win-x64"
rm -rf "$OUT"

echo "Publishing self-contained win-x64 build…"
dotnet publish CueMarkerExtractorApp/CueMarkerExtractorApp.csproj \
  -c Release -r win-x64 --self-contained true \
  -p:PublishSingleFile=true \
  -p:IncludeNativeLibrariesForSelfExtract=true \
  -p:DebugType=none \
  -o "$OUT"

# The Skia/HarfBuzz native packages ship prebuilt .pdb debug-symbol files
# that -p:DebugType=none can't suppress (they're package content, not
# generated by this build). They're only useful for native crash
# symbolication, not for running the app, so drop them to keep the
# deliverable to one file.
rm -f "$OUT"/*.pdb

echo "Done: $(pwd)/$OUT/CueMarkerExtractor.exe"
ls -lh "$OUT"
